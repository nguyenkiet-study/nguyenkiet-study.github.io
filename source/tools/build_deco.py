"""Kelvin decorative system: Modern Technology - Blue Flow.

Reads the SVG sources in design/deco/ and writes one CSS block into CSS.html
between the DECO:START / DECO:END markers. The block holds:
  * CSS variables with each SVG as a data URI (--deco-*)
  * base surfaces (--surface-light, --surface-navy, --glow-royal)
  * reusable utility classes (.bg-light-flow, .bg-navy-flow, .bg-navy-banner,
    .deco-dots, .deco-dots-navy, .deco-contours, .deco-contours-navy,
    .deco-facets, .deco-facets-navy, .deco-glow)
  * the mapping onto Kelvin's existing backgrounds (page, sign-in, navy banners)

Only backgrounds and decorative layers live here: no sizes, spacing, type or
colours of components. Every decorative pseudo-element is pointer-events:none
and sits behind the content.

Run:  python3 tools/build_deco.py   (then the usual build_gas / build_web / build_preview)
"""
import pathlib, re, urllib.parse

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'design' / 'deco'
CSS = ROOT / 'CSS.html'
START, END = '/* DECO:START */', '/* DECO:END */'


def uri(name):
    s = (SRC / name).read_text()
    # keep contour strokes hairline-thin however large the layer is scaled
    s = re.sub(r'<path (?=[^>]*stroke-width)', '<path vector-effect="non-scaling-stroke" ', s)
    s = re.sub(r'>\s+<', '><', s.strip())
    s = re.sub(r'\s{2,}', ' ', s)
    s = s.replace('"', "'")
    return 'url("data:image/svg+xml,' + urllib.parse.quote(s, safe=" '=/:;,.-()") + '")'


V = {k: uri(f) for k, f in [
    ('flow-light', 'flow-light.svg'), ('flow-navy', 'flow-navy.svg'), ('flow-banner', 'flow-banner.svg'),
    ('contour-light', 'contour-light.svg'), ('contour-navy', 'contour-navy.svg'),
    ('dots', 'dots.svg'), ('dots-navy', 'dots-navy.svg'),
    ('facets', 'facets.svg'), ('facets-navy', 'facets-navy.svg')]}

css = START + '''
/* ===== Kelvin decorative system: Modern Technology, Blue Flow =====
   Generated by tools/build_deco.py from design/deco/*.svg. Edit the SVGs, not this block.
   Backgrounds and decoration only. Layout, cards, type, buttons and navigation are untouched. */
:root{
''' + ''.join(f'  --deco-{k}:{v};\n' for k, v in V.items()) + '''  /* base surfaces */
  --surface-light:linear-gradient(160deg,#F9FBFE 0%,#F2F7FF 52%,#E7F0FF 100%);
  --surface-navy:linear-gradient(158deg,#132B63 0%,#10234F 42%,#0B1A3E 100%);
  --glow-royal:radial-gradient(75% 65% at 12% 0%,rgba(40,100,232,.38) 0%,rgba(40,100,232,0) 70%);
  --glow-soft:radial-gradient(closest-side,rgba(40,100,232,.10),rgba(40,100,232,0));
}

/* ---------- reusable surfaces (put on any block; content stays on top) ---------- */
.bg-light-flow{background:var(--deco-contour-light) right bottom/cover no-repeat,var(--deco-flow-light) right bottom/cover no-repeat,var(--surface-light)}
.bg-navy-flow{color:#fff;background:var(--deco-contour-navy) right bottom/cover no-repeat,var(--deco-flow-navy) right bottom/cover no-repeat,var(--glow-royal),var(--surface-navy)}
.bg-navy-banner{color:#fff;background:var(--deco-flow-banner) right bottom/cover no-repeat,var(--glow-royal),var(--surface-navy)}

/* ---------- reusable accent layers: drawn on a ::before behind the content ---------- */
.deco-dots,.deco-dots-navy,.deco-contours,.deco-contours-navy,.deco-facets,.deco-facets-navy,.deco-glow{position:relative;isolation:isolate}
.deco-dots::before,.deco-dots-navy::before,.deco-contours::before,.deco-contours-navy::before,.deco-facets::before,.deco-facets-navy::before,.deco-glow::before{content:"";position:absolute;inset:0;border-radius:inherit;pointer-events:none;z-index:-1;background-repeat:no-repeat}
.deco-dots::before{background-image:var(--deco-dots);background-position:right top;background-size:min(320px,70%) auto}
.deco-dots-navy::before{background-image:var(--deco-dots-navy);background-position:right top;background-size:min(320px,70%) auto}
.deco-contours::before{background-image:var(--deco-contour-light);background-position:right bottom;background-size:cover}
.deco-contours-navy::before{background-image:var(--deco-contour-navy);background-position:right bottom;background-size:cover}
.deco-facets::before{background-image:var(--deco-facets);background-position:right top;background-size:auto 100%}
.deco-facets-navy::before{background-image:var(--deco-facets-navy);background-position:right top;background-size:auto 100%}
.deco-glow::before{background-image:var(--glow-soft);background-position:0 0;background-size:100% 100%}

/* ---------- applied to Kelvin's existing backgrounds ---------- */
/* page: cloud-to-ice base */
body{background:var(--surface-light) fixed,var(--bg)}
/* app shell, top layer: ambient royal light top left, dot grid and two faint diagonal facets top right */
.app::before{content:"";position:fixed;inset:0;left:auto;width:100vw;height:100vh;pointer-events:none;z-index:0;
  background:var(--deco-dots) right 24px top 18px/340px auto no-repeat,
    var(--deco-facets) right -40px top 0/auto 62vh no-repeat,
    radial-gradient(60vw 50vh at 18% -10%,rgba(40,100,232,.09),rgba(40,100,232,0) 70%)}
/* app shell, bottom layer: the blue flow rising to the bottom right, behind the cards */
.app::after{content:"";position:fixed;right:0;bottom:0;width:min(1180px,86vw);height:min(560px,56vh);pointer-events:none;z-index:0;
  background:var(--deco-contour-light) right bottom/cover no-repeat,var(--deco-flow-light) right bottom/cover no-repeat;
  -webkit-mask-image:linear-gradient(to bottom,transparent 0,#000 38%);mask-image:linear-gradient(to bottom,transparent 0,#000 38%)}
.app>.main{position:relative;z-index:1}.app>.side{z-index:2}
/* sign-in: light side carries a low flow, the navy side the full navy treatment */
.auth{background:var(--deco-flow-light) left bottom/100% 38% no-repeat,var(--surface-light)}
.auth-panel{background:var(--deco-contour-navy) right bottom/100% 50% no-repeat,var(--deco-flow-navy) right bottom/100% 50% no-repeat,
  var(--deco-dots-navy) right 28px top 28px/300px auto no-repeat,var(--deco-facets-navy) right 0 top 0/auto 70% no-repeat,
  var(--glow-royal),var(--surface-navy)}
/* navy banners on finished screens and History */
.bolt-hero,.hx-hero{background:var(--deco-flow-banner) right bottom/cover no-repeat,var(--glow-royal),var(--surface-navy)}
@media(max-width:700px){
  .app::before{background:var(--deco-dots) right 10px top 10px/220px auto no-repeat,radial-gradient(90vw 40vh at 10% -10%,rgba(40,100,232,.08),rgba(40,100,232,0) 70%)}
  .app::after{width:100vw;height:38vh;opacity:.85}
  .auth{background-size:100% 26%,auto}
}
/* keep the focus screens calm on phones: no flow behind a running exercise */
body.in-session .app::after,body.in-test .app::after{opacity:.45}
@media print{.app::before,.app::after{display:none}body{background:#fff}}
''' + END

src = CSS.read_text()
if START in src:
    src = re.sub(re.escape(START) + '.*?' + re.escape(END), lambda m: css, src, flags=re.S)
else:
    src = src.rstrip()
    assert src.endswith('</style>')
    src += '\n<style>\n' + css + '\n</style>\n'
CSS.write_text(src)
print('deco block', len(css), 'bytes')
